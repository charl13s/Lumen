int drawText(raster::Canvas& c, int x, int y, const std::string& text,
             raster::Colour col, int scale) {
    if (scale < 1) scale = 1;
    int penX = x;

    for (char ch : text) {
        if (ch == '\n') continue;            // single line only
        const unsigned char* g = glyphFor(ch);

        for (int row = 0; row < kGlyphH; ++row) {
            const unsigned char bits = g[row];
            for (int colIdx = 0; colIdx < kGlyphW; ++colIdx) {
                // Bit 4 is the left pixel.
                if (!(bits & (1 << (kGlyphW - 1 - colIdx)))) continue;

                // Each pixel becomes a scale x scale block.
                for (int sy = 0; sy < scale; ++sy)
                    for (int sx = 0; sx < scale; ++sx)
                        c.set(penX + colIdx * scale + sx,
                              y + row * scale + sy, col);
            }
        }
        penX += kAdvance * scale;
    }
    return penX;
}

int textWidth(const std::string& text, int scale) {
    if (scale < 1) scale = 1;
    if (text.empty()) return 0;
    // Every letter is the same width; drop the gap after the last one.
    return static_cast<int>(text.size()) * kAdvance * scale - scale;
}

int drawTextCentred(raster::Canvas& c, int cx, int y, const std::string& text,
                    raster::Colour col, int scale) {
    return drawText(c, cx - textWidth(text, scale) / 2, y, text, col, scale);
}

